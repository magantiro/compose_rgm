#!/usr/bin/env python3
"""Generate experiments/INDEX.md from what the apps actually declare.

Every Modal experiment is invoked as

    modal run modal_apps/<app>.py::<entrypoint> [--flags]

but nothing in the tree records which entrypoints exist, what they do, or what
they take. That is the real reproducibility gap: the code is fine, it is simply
undiscoverable. This walks the apps with `ast`, extracts each
`@app.local_entrypoint()` function, its parameters and defaults, and the first
line of its docstring, and writes the table.

Nothing is invented: every row is read out of the source, so the index cannot
drift into describing experiments that do not exist.

Usage:  python3 tools/gen_experiment_index.py [--write]
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPS = ROOT / "modal_apps"


def first_line(node) -> str:
    d = ast.get_docstring(node) or ""
    return d.strip().split("\n")[0] if d else ""


def signature(fn: ast.FunctionDef) -> str:
    args = fn.args
    defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
    parts = []
    for a, d in zip(args.args, defaults):
        if d is None:
            parts.append(f"--{a.arg.replace('_', '-')}")
        else:
            try:
                v = ast.literal_eval(d)
            except (SyntaxError, ValueError):
                v = "?"
            parts.append(f"--{a.arg.replace('_', '-')} {v}")
    return " ".join(parts)


def scan() -> list[dict]:
    rows = []
    for p in sorted(APPS.glob("*.py")):
        try:
            tree = ast.parse(p.read_text(errors="ignore"))
        except SyntaxError:
            continue
        mod_doc = first_line(tree)
        entries = []
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef):
                continue
            for dec in node.decorator_list:
                src = ast.dump(dec)
                if "local_entrypoint" in src:
                    entries.append(
                        {
                            "name": node.name,
                            "doc": first_line(node),
                            "sig": signature(node),
                        }
                    )
        if entries:
            rows.append({"app": p.name, "doc": mod_doc, "entries": entries})
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    rows = scan()
    n_entries = sum(len(r["entries"]) for r in rows)
    out = [
        "# Experiment index",
        "",
        (
            f"*Generated by `tools/gen_experiment_index.py` from the source. "
            f"{len(rows)} apps, {n_entries} runnable entrypoints. "
            f"Regenerate after adding an entrypoint; do not hand-edit.*"
        ),
        "",
        "The commands below expose each app's local entrypoints. Obey the experiment-specific",
        "contract before launching: some long drivers require `modal deploy` plus a durable",
        "spawn launcher and must not be started with `modal run --detach`.",
        "",
    ]
    for r in rows:
        out.append(f"## `{r['app']}`")
        if r["doc"]:
            out.append(f"{r['doc']}")
        out.append("")
        for e in r["entries"]:
            cmd = f"modal run modal_apps/{r['app']}::{e['name']}"
            if e["sig"]:
                cmd += " " + e["sig"]
            out.append(f"- **`{e['name']}`** — {e['doc'] or '_no docstring_'}")
            out.append("  ```")
            out.append(f"  {cmd}")
            out.append("  ```")
        out.append("")
    text = "\n".join(out)
    if args.write:
        d = ROOT / "experiments"
        d.mkdir(exist_ok=True)
        (d / "INDEX.md").write_text(text)
        print(f"wrote experiments/INDEX.md ({len(rows)} apps, {n_entries} entrypoints)")
    else:
        print(text[:1500])


if __name__ == "__main__":
    main()
