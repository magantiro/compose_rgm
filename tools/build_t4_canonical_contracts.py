"""Build and seal the three canonical T4 arm contracts from ONE shared configuration.

The three contracts are produced by one function from one ``SHARED_CONTROLLER`` dict,
so they cannot drift: ``controller_identity`` is recomputed over each sealed payload
and the builder REFUSES to write anything unless all three agree. Only three fields
differ, and each is declared rather than implied:

    experts                        the arm's proposal vocabulary
    adaptive_support_expansion     an explicit boolean
    support_expansion              present iff that boolean is true

Cells are generated by ``t4_canonical_controller.canonical_cells`` from the published
seed registry, so the source molecules, the deltas and the per-cell RNG seeds are a
pure function of the benchmark inputs and are byte-identical across arms wherever a
cell appears in more than one.

Usage::

    python3 tools/build_t4_canonical_contracts.py --status draft
    python3 tools/build_t4_canonical_contracts.py --status authorized
"""

