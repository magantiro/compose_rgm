SCIENTIFIC_PROBLEM = (
    "Does one frozen controller -- local executable programs, coordinated structural "
    "programs, and state-dependent adaptive support expansion inside one validity-closed "
    "molecular process -- work across the whole T4 panel without per-target adaptation, "
    "and what does each component contribute?"
)


def _git_revision() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def build_arm(arm: str, *, status: str, seeds: list[dict]) -> dict:
    spec = ARMS[arm]
    cells = canonical_cells(seeds, spec["deltas"])
    payload: dict = {
        "schema_version": "t4_canonical_shared_controller_contract_v1",
        "status": status,
        "arm": spec["arm"],
        "arm_name": spec["arm_name"],
        "arm_isolates": spec["isolates"],
        "scientific_problem": SCIENTIFIC_PROBLEM,
        "primary_model_output": (
            "a docking-feedback-adapted selection over complete executable COMPOSE "
            "programs drawn from the arm's declared proposal vocabulary"
        ),
        "prospective_primary": "C",
        "cells": cells,
        "cell_identity_sha256": cell_identity_digest(cells),
        "deltas": [float(value) for value in spec["deltas"]],
        "experts": list(spec["experts"]),
        "adaptive_support_expansion": bool(spec["adaptive_support_expansion"]),
        "expansion_trigger_min_eligible": (
            EXPANSION_TRIGGER_MIN_ELIGIBLE if spec["adaptive_support_expansion"] else 0
        ),
        "total_charged_call_ceiling": len(cells) * SHARED_CONTROLLER["charged_calls_per_cell"],
        "evaluator_sha256": {"qvina02": QVINA02_SHA256},
        "round_lock_policy": {
            "publish_complete_candidate_pool_before_docking": True,
            "no_backfill": True,
            "no_candidate_replacement": True,
            "automatic_docking_retries": 0,
            "persist_after_every_round_including_root": True,
        },
        "claim_boundary": CLAIM_BOUNDARY,
        "code_revision": _git_revision(),
    }
    payload.update({key: value for key, value in SHARED_CONTROLLER.items()})
    if spec["adaptive_support_expansion"]:
        payload["support_expansion"] = dict(ADAPTIVE_SUPPORT_EXPANSION)
    payload["runtime_inputs_sha256"] = {
        relative: sha256_file(ROOT / relative) for relative in sorted(RUNTIME_INPUTS)
    }
    return payload


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--status", choices=("draft", "authorized"), required=True)
    args = parser.parse_args()
    status = {
        "draft": "DRAFT_NOT_AUTHORIZED",
        "authorized": "AUTHORIZED_T4_CANONICAL_SHARED_CONTROLLER_15000_CALLS",
    }[args.status]

    seeds = load_seeds(ROOT / SEEDS)
    payloads = {arm: build_arm(arm, status=status, seeds=seeds) for arm in sorted(ARMS)}

    # The three arms MUST agree on the shared controller. A builder that can emit three
    # contracts which merely look alike is not evidence that one controller ran.
    identities = {arm: controller_identity(payload) for arm, payload in payloads.items()}
    if len(set(identities.values())) != 1:
        raise SystemExit(f"arms disagree on the shared controller: {identities}")

    # Cells that appear in more than one arm must be byte-identical inputs.
    by_cell: dict[str, dict] = {}
    for arm, payload in payloads.items():
        for cell in payload["cells"]:
            previous = by_cell.setdefault(cell["cell"], cell)
            if previous != cell:
                raise SystemExit(f"cell {cell['cell']!r} differs between arms")

    total = sum(payload["total_charged_call_ceiling"] for payload in payloads.values())
    report = {
        "controller_identity_sha256": next(iter(set(identities.values()))),
        "total_charged_call_ceiling": total,
        "arms": {},
    }
    for arm in sorted(payloads):
        payload = payloads[arm]
        destination = ROOT / TARGET[arm]
        seal(destination, payload)
        report["arms"][arm] = {
            "path": TARGET[arm],
            "payload_sha256": identity(payload),
            "file_sha256": sha256_file(destination),
            "cells": len(payload["cells"]),
            "experts": payload["experts"],
            "adaptive": payload["adaptive_support_expansion"],
            "ceiling": payload["total_charged_call_ceiling"],
        }
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
