#!/usr/bin/env python3
"""Compile config_registry.yaml + results_registry.yaml into results.tex.

results.tex defines, for the LaTeX side (see math_commands.tex):

  * the draft/final mode toggle (\\draftmodetrue / \\draftmodefalse);
  * one storage macro per config key   (\\defconfigvalue{KEY}{VALUE});
  * one storage macro per result key
        - final:   \\defresultvalue{KEY}{VALUE}{CI}{UNIT}
        - pending: \\defresultpending{KEY}{UNIT} ;
  * one storage macro per result sentence (\\defresultsentence{KEY}{TEMPLATE}).

Grids in results_registry.yaml expand to pending scalar keys
``<prefix>_<metric.key>_<method.key>``.

The script never invents a value: pending stays pending. In DRAFT mode every
pending key still renders (as a loud placeholder) so the paper compiles; in
FINAL mode a pending key is a hard error at the LaTeX level *and* is caught
earlier by check_placeholders.py.

Usage:
    build_results_tex.py --mode {draft,final} [--config ...] [--results ...] [--out ...]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent


def _tex_escape_value(text: str) -> str:
    """Values are authored as LaTeX-ready strings in the registry (they may
    contain macros like \\approx or escaped \\%). We pass them through verbatim;
    the registry is the single place a value's LaTeX form is authored."""
    return str(text)


_UNIT_ESCAPE = {"%": r"\%", "&": r"\&", "#": r"\#", "$": r"\$", "_": r"\_"}


def _tex_escape_unit(text: str) -> str:
    """Units are plain display labels, so TeX specials must be escaped (a bare
    '%' would comment out the rest of the generated line)."""
    return "".join(_UNIT_ESCAPE.get(ch, ch) for ch in str(text))


def load_yaml(path: Path) -> dict:
    with path.open() as fh:
        return yaml.safe_load(fh) or {}


def expand_grids(results: dict) -> dict[str, dict]:
    """Return {key: record} for every grid-expanded pending scalar key."""
    expanded: dict[str, dict] = {}
    for grid in results.get("grids", []) or []:
        prefix = grid["prefix"]
        for metric in grid["metrics"]:
            for method in grid["methods"]:
                key = f"{prefix}_{metric['key']}_{method['key']}"
                expanded[key] = {
                    "status": "pending",
                    "value": None,
                    "ci": None,
                    "unit": metric.get("unit", ""),
                    "direction": metric.get("direction", "none"),
                    "description": f"{metric.get('description','')} [{method['label']}]",
                    "claim_key": grid.get("claim_key", ""),
                    "resampling_unit": grid.get("resampling_unit", ""),
                }
    return expanded


def collect_result_keys(results: dict) -> dict[str, dict]:
    keys: dict[str, dict] = {}
    for key, rec in (results.get("results", {}) or {}).items():
        keys[key] = rec
    for key, rec in expand_grids(results).items():
        if key in keys:
            raise SystemExit(f"grid key collides with an explicit result key: {key}")
    keys.update(expand_grids(results))
    return keys


def emit(mode: str, config: dict, results: dict) -> tuple[str, list[str]]:
    """Return (results.tex body, list of pending keys)."""
    lines: list[str] = []
    pending: list[str] = []
    lines.append("% !! AUTO-GENERATED by scripts/build_results_tex.py -- DO NOT EDIT BY HAND !!")
    lines.append(f"% mode = {mode}")
    lines.append("\\makeatletter")
    lines.append("\\draftmodetrue" if mode == "draft" else "\\draftmodefalse")

    # ---- config values -------------------------------------------------------
    lines.append("% ---- config values ----")
    for key, rec in config.items():
        if not isinstance(rec, dict) or "value" not in rec:
            continue
        lines.append(f"\\defconfigvalue{{{key}}}{{{_tex_escape_value(rec['value'])}}}")

    # ---- result values / pendings -------------------------------------------
    lines.append("% ---- results ----")
    for key, rec in collect_result_keys(results).items():
        if rec.get("kind") == "sentence":
            template = " ".join(str(rec.get("template", "")).split())
            lines.append(f"\\defresultsentence{{{key}}}{{{template}}}")
            if rec.get("status", "pending") != "final":
                pending.append(key)
            continue
        unit = _tex_escape_unit(rec.get("unit", ""))
        if rec.get("status") == "final" and rec.get("value") is not None:
            value = _tex_escape_value(rec["value"])
            ci = rec.get("ci")
            ci_str = "" if not ci else f"[{ci[0]}, {ci[1]}]"
            lines.append(f"\\defresultvalue{{{key}}}{{{value}}}{{{ci_str}}}{{{unit}}}")
        else:
            lines.append(f"\\defresultpending{{{key}}}{{{unit}}}")
            pending.append(key)

    lines.append("\\makeatother")
    return "\n".join(lines) + "\n", pending


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["draft", "final"], default="draft")
    ap.add_argument("--config", type=Path, default=PAPER / "config_registry.yaml")
    ap.add_argument("--results", type=Path, default=PAPER / "results_registry.yaml")
    ap.add_argument("--out", type=Path, default=PAPER / "results.tex")
    args = ap.parse_args()

    config = load_yaml(args.config)
    results = load_yaml(args.results)
    body, pending = emit(args.mode, config, results)
    args.out.write_text(body)

    n_conf = sum(1 for r in config.values() if isinstance(r, dict) and "value" in r)
    print(f"[build_results_tex] mode={args.mode} config_values={n_conf} "
          f"pending_results={len(pending)} -> {args.out.relative_to(PAPER)}")
    if args.mode == "final" and pending:
        print("[build_results_tex] FINAL mode with pending results present:", file=sys.stderr)
        for k in pending:
            print(f"    pending: {k}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
